// Тест фічі F-010. Піднімає справжній сервер і справжні сокети.
//
// Клієнт у тесті — «спостерігач»: він пише в історію кожен список, що прийшов,
// з моменту відкриття сокета. Чекати «наступного повідомлення» не можна — при
// кількох клієнтах розсилок кілька, і та, на яку чекаєш, могла прийти ще до
// того, як ти підписався. Перша версія цього тесту падала саме так.
//
// Це зародок стенду F-009: тут уже є кілька клієнтів і справжня мережа.
import { describe, it, expect, afterEach } from 'vitest';
import WebSocket from 'ws';
import type { ВідСервера, Клієнт, Роль } from '../packages/protocol/src/index.js';
import { підняти, type Сервер } from '../apps/server/src/index.js';
import { пауза, рольЗАдреси } from '../apps/web/src/звязок.js';

let сервер: Сервер | null = null;
const спостерігачі: Спостерігач[] = [];

afterEach(async () => {
  for (const с of спостерігачі) с.сокет.close();
  спостерігачі.length = 0;
  await сервер?.закрити();
  сервер = null;
});

interface Спостерігач {
  сокет: WebSocket;
  я: string;
  /** Усі списки клієнтів, що прийшли, у порядку надходження. */
  історія: Клієнт[][];
  помилки: string[];
  /**
   * Чекає стану, що задовольняє умову, дивлячись і в історію, і в нові повідомлення.
   * `від` — індекс в історії, з якого починати шукати. Потрібен, коли перевіряєш
   * наслідок дії: без нього умова «список із одного» зійдеться на найпершому
   * повідомленні, коли майстер справді був один. Бери позначку перед дією:
   * `const п = с.історія.length` → дія → `дочекатись(умова, { від: п })`.
   */
  дочекатись: (
    умова: (к: Клієнт[]) => boolean,
    опції?: { від?: number; мс?: number },
  ) => Promise<Клієнт[]>;
}

function спостерігати(сокет: WebSocket): Спостерігач {
  const історія: Клієнт[][] = [];
  const помилки: string[] = [];
  const слухачі = new Set<() => void>();

  сокет.on('message', (сире: Buffer) => {
    let м: ВідСервера;
    try {
      м = JSON.parse(сире.toString('utf8')) as ВідСервера;
    } catch {
      помилки.push('не JSON від сервера');
      return;
    }
    if (м.тип === 'вітаємо' || м.тип === 'клієнти') історія.push(м.клієнти);
    else if (м.тип === 'помилка') помилки.push(м.текст);
    for (const с of [...слухачі]) с();
  });

  const с: Спостерігач = {
    сокет,
    я: '',
    історія,
    помилки,
    дочекатись: (умова, опції = {}) => {
      const від = опції.від ?? 0;
      const мс = опції.мс ?? 3000;
      return new Promise<Клієнт[]>((готово, зле) => {
        const перевірити = (): boolean => {
          const знайдено = історія.slice(від).find(умова);
          if (знайдено === undefined) return false;
          готово(знайдено);
          return true;
        };
        if (перевірити()) return;
        const годинник = setTimeout(() => {
          слухачі.delete(слухач);
          зле(
            new Error(
              `умова не виконалась за ${мс} мс; довжини списків в історії: ` +
                `[${історія.map((і) => і.length).join(', ')}]`,
            ),
          );
        }, мс);
        const слухач = (): void => {
          if (перевірити()) {
            clearTimeout(годинник);
            слухачі.delete(слухач);
          }
        };
        слухачі.add(слухач);
      });
    },
  };
  спостерігачі.push(с);
  return с;
}

async function підключити(порт: number, роль: Роль, персонаж?: string): Promise<Спостерігач> {
  const сокет = new WebSocket(`ws://127.0.0.1:${порт}`);
  await new Promise<void>((готово, зле) => {
    сокет.once('open', готово);
    сокет.once('error', зле);
  });
  // Спостерігач підключається ДО привітання, тому жодне повідомлення не втрачається
  const с = спостерігати(сокет);
  сокет.send(JSON.stringify({ тип: 'привітання', роль, персонаж }));
  const перший = await с.дочекатись((к) => к.length >= 1);
  с.я = перший.find((к) => к.роль === роль && к.персонаж === персонаж)?.id ?? '';
  return с;
}

describe('F-010 · сервер і підключення', () => {
  it('віддає стан здоровʼя', async () => {
    сервер = await підняти(0);
    const відповідь = await fetch(`http://127.0.0.1:${сервер.порт}/health`);
    expect(відповідь.status).toBe(200);
    expect(await відповідь.json()).toEqual({ живий: true, підключених: 0 });
  });

  it('майстер підключається і бачить себе одного', async () => {
    сервер = await підняти(0);
    const майстер = await підключити(сервер.порт, 'gm');
    const список = await майстер.дочекатись((к) => к.length === 1);
    expect(список[0]?.роль).toBe('gm');
    expect(список[0]?.id).toBe(майстер.я);
  });

  it('майстер і три гравці бачать однаковий список із чотирьох', async () => {
    сервер = await підняти(0);
    const майстер = await підключити(сервер.порт, 'gm');
    const гравець1 = await підключити(сервер.порт, 'player', 'krinzh-dor');
    const гравець2 = await підключити(сервер.порт, 'player', 'sandra-vong');
    const гравець3 = await підключити(сервер.порт, 'player', 'nigra-4');

    expect(сервер.скількиПідключених()).toBe(4);

    const уМайстра = await майстер.дочекатись((к) => к.length === 4);
    expect(уМайстра.map((к) => к.роль)).toEqual(['gm', 'player', 'player', 'player']);
    expect(уМайстра.map((к) => к.персонаж)).toEqual([
      undefined, 'krinzh-dor', 'sandra-vong', 'nigra-4',
    ]);

    // Головне у фічі: однаковий список у всіх, а не лише в майстра
    for (const гравець of [гравець1, гравець2, гравець3]) {
      const уГравця = await гравець.дочекатись((к) => к.length === 4);
      expect(уГравця.map((к) => к.id)).toEqual(уМайстра.map((к) => к.id));
    }
  });

  it('коли гравець відпав, решта це бачить', async () => {
    сервер = await підняти(0);
    const майстер = await підключити(сервер.порт, 'gm');
    const гравець = await підключити(сервер.порт, 'player', 'alister');
    await майстер.дочекатись((к) => к.length === 2);

    // Позначка перед дією: інакше умова зійдеться на найпершому повідомленні,
    // коли майстер справді був один — і тест пройде, нічого не перевіривши
    const позначка = майстер.історія.length;
    гравець.сокет.close();
    const післяВідпадання = await майстер.дочекатись((к) => к.length === 1, {
      від: позначка,
    });
    expect(післяВідпадання).toHaveLength(1);
    expect(сервер.скількиПідключених()).toBe(1);
  });

  it('сміття замість привітання не ламає сервер', async () => {
    сервер = await підняти(0);
    const сокет = new WebSocket(`ws://127.0.0.1:${сервер.порт}`);
    await new Promise<void>((готово) => сокет.once('open', готово));
    const с = спостерігати(сокет);

    сокет.send('це не json');
    сокет.send(JSON.stringify({ тип: 'привіт', роль: 'король' }));
    await new Promise((готово) => setTimeout(готово, 150));

    expect(с.помилки).toEqual(['не JSON', 'не зрозумів привітання']);
    expect(с.історія).toHaveLength(0);
    expect(сервер.скількиПідключених()).toBe(0);
  });

  it('майстер може бути не один — обмежень на роль немає', async () => {
    сервер = await підняти(0);
    const перший = await підключити(сервер.порт, 'gm');
    await підключити(сервер.порт, 'gm');
    const список = await перший.дочекатись((к) => к.length === 2);
    expect(список.every((к) => к.роль === 'gm')).toBe(true);
  });
});

describe('F-010 · розбір адреси й перепідключення', () => {
  it('роль і персонаж читаються з адреси', () => {
    expect(рольЗАдреси('?as=gm')).toEqual({ роль: 'gm' });
    expect(рольЗАдреси('?as=player&character=krinzh-dor')).toEqual({
      роль: 'player', персонаж: 'krinzh-dor',
    });
    expect(рольЗАдреси('')).toEqual({ роль: 'player' });
    expect(рольЗАдреси('?as=player&character=')).toEqual({ роль: 'player' });
  });

  it('пауза між спробами росте, але не більше 5 секунд', () => {
    expect(пауза(1)).toBe(300);
    expect(пауза(2)).toBe(600);
    expect(пауза(3)).toBe(1200);
    expect(пауза(99)).toBe(5000);
  });
});
