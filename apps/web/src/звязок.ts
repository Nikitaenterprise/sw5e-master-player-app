// Звʼязок із сервером. Тримає сокет живим і повідомляє, хто онлайн.
//
// Клієнт ніколи не вважає себе джерелом правди: він надсилає привітання й слухає.
// Якщо сокет обірвався — перепідключається сам, бо за столом ніхто не має
// перезавантажувати сторінку на телефоні через провал wifi на дві секунди.
import type { Клієнт, Роль, ДоСервера, ВідСервера } from '@holotable/protocol';

export type Стан =
  | { статус: 'підключаюсь' }
  | { статус: 'онлайн'; я: string; клієнти: Клієнт[] }
  | { статус: 'обірвано'; черезМс: number }
  | { статус: 'помилка'; текст: string };

export interface Параметри {
  роль: Роль;
  персонаж?: string;
  наЗміну: (стан: Стан) => void;
}

/** Читає роль і персонажа з адреси: ?as=gm або ?as=player&character=krinzh-dor */
export function рольЗАдреси(пошук: string): { роль: Роль; персонаж?: string } {
  const п = new URLSearchParams(пошук);
  const роль: Роль = п.get('as') === 'gm' ? 'gm' : 'player';
  const персонаж = п.get('character');
  return персонаж === null || персонаж === '' ? { роль } : { роль, персонаж };
}

/** Пауза перед наступною спробою: росте, але не довше 5 секунд. */
export function пауза(спроба: number): number {
  return Math.min(5000, 300 * 2 ** Math.max(0, спроба - 1));
}

export function підключитись({ роль, персонаж, наЗміну }: Параметри): () => void {
  let сокет: WebSocket | null = null;
  let таймер: number | undefined;
  let закрито = false;
  let спроба = 0;
  let мійId = '';

  const відкрити = (): void => {
    if (закрито) return;
    наЗміну({ статус: 'підключаюсь' });

    const схема = location.protocol === 'https:' ? 'wss:' : 'ws:';
    сокет = new WebSocket(`${схема}//${location.host}`);

    сокет.addEventListener('open', () => {
      спроба = 0;
      const привітання: ДоСервера = {
        тип: 'привітання',
        роль,
        ...(персонаж === undefined ? {} : { персонаж }),
      };
      сокет?.send(JSON.stringify(привітання));
    });

    сокет.addEventListener('message', (под) => {
      let м: ВідСервера;
      try {
        м = JSON.parse(String(под.data)) as ВідСервера;
      } catch {
        return;
      }
      switch (м.тип) {
        case 'вітаємо':
          мійId = м.я;
          наЗміну({ статус: 'онлайн', я: мійId, клієнти: м.клієнти });
          break;
        case 'клієнти':
          наЗміну({ статус: 'онлайн', я: мійId, клієнти: м.клієнти });
          break;
        case 'помилка':
          наЗміну({ статус: 'помилка', текст: м.текст });
          break;
      }
    });

    сокет.addEventListener('close', () => {
      if (закрито) return;
      спроба += 1;
      const мс = пауза(спроба);
      наЗміну({ статус: 'обірвано', черезМс: мс });
      таймер = window.setTimeout(відкрити, мс);
    });
  };

  відкрити();

  return () => {
    закрито = true;
    if (таймер !== undefined) window.clearTimeout(таймер);
    сокет?.close();
  };
}
