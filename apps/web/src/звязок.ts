// Звʼязок із сервером: сокет, перепідключення, і весь стан, що приходить.
//
// Клієнт ніколи не вважає себе джерелом правди (ADR 0002). Він надсилає наміри й
// слухає події. Якщо сокет обірвався — перепідключається сам, бо за столом ніхто
// не має перезавантажувати сторінку на телефоні через провал wifi на дві секунди.
import type {
  Клієнт,
  Роль,
  ДоСервера,
  ВідСервера,
  Подія,
  СтанПерсонажа,
} from '@holotable/protocol';

export type Звязок =
  | { статус: 'підключаюсь' }
  | { статус: 'онлайн' }
  | { статус: 'обірвано'; черезМс: number }
  | { статус: 'помилка'; текст: string };

export interface Знімок {
  звязок: Звязок;
  я: string;
  клієнти: Клієнт[];
  персонажі: Record<string, СтанПерсонажа>;
  /** Останні події, найновіші спереду. Основа потоку сповіщень майстру (F-022). */
  події: Подія[];
  /** Остання відмова сервера — щоб гравець бачив, чому не вийшло. */
  відмова: string | null;
}

export const ПОРОЖНІЙ: Знімок = {
  звязок: { статус: 'підключаюсь' },
  я: '',
  клієнти: [],
  персонажі: {},
  події: [],
  відмова: null,
};

/** Читає роль і персонажа з адреси: ?as=gm або ?as=player&character=krinzh-dor */
export function рольЗАдреси(пошук: string): { роль: Роль; персонаж?: string } {
  const п = new URLSearchParams(пошук);
  const роль: Роль = п.get('as') === 'gm' ? 'gm' : 'player';
  const персонаж = п.get('character');
  return персонаж === null || персонаж === '' ? { роль } : { роль, персонаж };
}

/** Пауза перед наступною спробою: росте, але не довше 5 секунд. */
export function пауза(спроба: number): number {
  return Math.min(5000, 300 * 2 ** Math.max(0, спроба - 1));
}

export interface Керування {
  /** Надіслати намір змінити стан. Сервер вирішує, чи можна. */
  змінити: (персонаж: string, зміни: СтанПерсонажа, нотатка?: string) => void;
  відключитись: () => void;
}

export function підключитись(
  роль: Роль,
  персонаж: string | undefined,
  наЗміну: (знімок: Знімок) => void,
): Керування {
  let знімок: Знімок = { ...ПОРОЖНІЙ };
  let сокет: WebSocket | null = null;
  let таймер: number | undefined;
  let закрито = false;
  let спроба = 0;

  const оновити = (частина: Partial<Знімок>): void => {
    знімок = { ...знімок, ...частина };
    наЗміну(знімок);
  };

  const відкрити = (): void => {
    if (закрито) return;
    оновити({ звязок: { статус: 'підключаюсь' } });

    const схема = location.protocol === 'https:' ? 'wss:' : 'ws:';
    сокет = new WebSocket(`${схема}//${location.host}`);

    сокет.addEventListener('open', () => {
      спроба = 0;
      const привітання: ДоСервера = {
        тип: 'привітання',
        роль,
        ...(персонаж === undefined ? {} : { персонаж }),
      };
      сокет?.send(JSON.stringify(привітання));
    });

    сокет.addEventListener('message', (под) => {
      let м: ВідСервера;
      try {
        м = JSON.parse(String(под.data)) as ВідСервера;
      } catch {
        return;
      }
      switch (м.тип) {
        case 'вітаємо':
          оновити({ звязок: { статус: 'онлайн' }, я: м.я, клієнти: м.клієнти });
          break;
        case 'клієнти':
          оновити({ клієнти: м.клієнти });
          break;
        case 'стан':
          оновити({ персонажі: м.персонажі });
          break;
        case 'подія':
          оновити({
            персонажі: { ...знімок.персонажі, [м.подія.персонаж]: м.стан },
            події: [м.подія, ...знімок.події].slice(0, 100),
            відмова: null,
          });
          break;
        case 'відмова':
          оновити({ відмова: м.причина });
          break;
        case 'помилка':
          оновити({ звязок: { статус: 'помилка', текст: м.текст } });
          break;
      }
    });

    сокет.addEventListener('close', () => {
      if (закрито) return;
      спроба += 1;
      const мс = пауза(спроба);
      оновити({ звязок: { статус: 'обірвано', черезМс: мс } });
      таймер = window.setTimeout(відкрити, мс);
    });
  };

  відкрити();

  return {
    змінити: (кого, зміни, нотатка) => {
      if (сокет?.readyState !== 1) return;
      const намір: ДоСервера = {
        тип: 'намір',
        персонаж: кого,
        зміни,
        ...(нотатка === undefined ? {} : { нотатка }),
      };
      сокет.send(JSON.stringify(намір));
    },
    відключитись: () => {
      закрито = true;
      if (таймер !== undefined) window.clearTimeout(таймер);
      сокет?.close();
    },
  };
}
