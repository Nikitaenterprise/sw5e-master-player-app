// Відкриває сторінку в браузері власника після старту сервера.
// Потрібно, щоб ЗАПУСТИТИ.bat був справді «подвійний клік і грай»: без цього
// власник мусив би копіювати адресу з терміналу.
import { exec } from 'node:child_process';

export function відкритиВБраузері(посилання: string): void {
  const команда =
    process.platform === 'win32'
      ? `start "" "${посилання}"`
      : process.platform === 'darwin'
        ? `open "${посилання}"`
        : `xdg-open "${посилання}"`;
  // Якщо не вийшло — не падаємо: адреса все одно надрукована в терміналі
  exec(команда, () => undefined);
}
